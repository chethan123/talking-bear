/**
 * The DOM pointer adapter (plan §4.6.3, issue #87): the thin layer between the stage canvas's Pointer Events and
 * the pure recogniser in `recognizer.ts`. It owns the recogniser state and hands every emitted gesture to
 * `onGesture`.
 *
 * **Samples.** Each `pointerdown`, `pointerup` and `pointercancel` becomes one sample, and each `pointermove` one
 * sample per coalesced event (`getCoalescedEvents()`; the event itself when that list is missing or empty).
 * Positions are CSS px relative to the canvas, from the `getBoundingClientRect()` read at the latest
 * `pointerdown`. A sample's `t` is **its own event's** `timeStamp` (a coalesced event's, not the dispatched
 * event's), which shares `performance.now()`'s time origin; `id` and `pointerType` come from the dispatched event.
 * Moves, ups and cancels of a pointer that is not down on the canvas (a hovering mouse) are not fed.
 *
 * **Ticks.** `tick()` runs every animation frame. While a pointer is down it feeds
 * `{ id: -1, t: now(), x: 0, y: 0, type: 'tick' }` (pointer id -1 is reserved for events not generated by a
 * pointing device), so long-press fires without movement. With no pointer down it returns at once: the
 * recogniser's tick only acts on pointers that are down, so an idle frame feeds and allocates nothing.
 *
 * **DOM hygiene** (plan §4.6.3, X-A5): inline `touch-action: none` and `user-select: none` on the canvas
 * (restored by `detach`), `contextmenu` and `selectstart` default actions prevented, and pointer capture for the
 * mouse (touch captures implicitly; the browser releases capture itself after `pointerup` / `pointercancel`).
 *
 * **Activation hooks** for haptics (#92) and the director's release (#93): `onRawDown` on every `pointerdown`,
 * before its gestures; `onRawUp` on every `pointerup` and `pointercancel`, after that sample's gestures and after
 * the pointer has left the active set, with `active` the number of pointers still down.
 */
import { initialRecState, recognize } from './recognizer.ts';
import type { Gesture, PointerSample, RecState } from './recognizer.ts';
import type { RegionId } from './region-ids.ts';

export interface PointerAdapterOptions {
  /** Hit-tests a point in CSS px relative to the canvas. */
  hit: (x: number, y: number) => RegionId;
  /** The clock for tick samples only (ms, `performance.now()`'s time origin). Default `performance.now()`. */
  now?: () => number;
  onGesture(g: Gesture): void;
  onRawDown?(): void;
  onRawUp?(e: { cancel: boolean; active: number }): void;
  /** Called with every sample passed to `recognize`, just before it is fed. */
  onSample?(s: PointerSample): void;
}

export interface PointerAdapter {
  /**
   * Removes every listener, releases mouse capture, restores the canvas styles; later events and ticks do nothing.
   * It may be called from any callback: no further callback of the current event runs (not even `hit`).
   */
  detach(): void;
  /** Feeds a tick sample while a pointer is down; call once per animation frame. */
  tick(): void;
}

/** The inline canvas styles the adapter sets to `none` while attached. */
const HYGIENE_STYLES = ['touch-action', 'user-select'] as const;
/** Pointer Events 3 reserves pointer id -1 for events not generated by a pointing device. */
const TICK_ID = -1;
/** The pointer listeners never call `preventDefault`. */
const PASSIVE: AddEventListenerOptions = { passive: true };

function pointerTypeOf(e: PointerEvent): PointerSample['pointerType'] {
  const p = e.pointerType;
  return p === 'touch' || p === 'mouse' || p === 'pen' ? p : undefined;
}

export function attachPointerAdapter(canvas: HTMLCanvasElement, opts: PointerAdapterOptions): PointerAdapter {
  const now = opts.now ?? (() => performance.now());
  let state: RecState = initialRecState();
  /** The pointers down on the canvas (fed a `down`, not yet an `up` or `cancel`). */
  const active = new Set<number>();
  /** The canvas's viewport position at the latest `pointerdown`. */
  let left = 0;
  let top = 0;
  let attached = true;

  const style = canvas.style;
  const saved = HYGIENE_STYLES.map((name) => ({
    name,
    value: style.getPropertyValue(name),
    priority: style.getPropertyPriority(name),
  }));
  for (const name of HYGIENE_STYLES) style.setProperty(name, 'none');

  /** Feeds one sample. Any callback may call `detach()`, so `attached` is re-read after each one. */
  function feed(s: PointerSample): void {
    if (!attached) return;
    opts.onSample?.(s);
    // Detached by onSample: no hit test, no recogniser state, no gestures.
    if (!attached) return;
    const r = recognize(state, s, opts.hit);
    state = r[0];
    const gestures = r[1];
    for (let i = 0; i < gestures.length; i++) {
      // Detached by an earlier onGesture: the rest of this sample's gestures are dropped.
      if (!attached) return;
      opts.onGesture(gestures[i]!);
    }
  }

  /** A sample of pointer `e` at event `at` (`e` itself, or one of its coalesced events). */
  function sample(e: PointerEvent, at: PointerEvent, type: PointerSample['type']): PointerSample {
    return {
      id: e.pointerId,
      t: at.timeStamp,
      x: at.clientX - left,
      y: at.clientY - top,
      type,
      pointerType: pointerTypeOf(e),
    };
  }

  const onDown = (e: PointerEvent): void => {
    const rect = canvas.getBoundingClientRect();
    left = rect.left;
    top = rect.top;
    if (e.pointerType === 'mouse') {
      try {
        canvas.setPointerCapture(e.pointerId);
      } catch {
        // NotFoundError for a pointer id that is not active (synthetic events): the gesture works without capture.
      }
    }
    active.add(e.pointerId);
    opts.onRawDown?.();
    feed(sample(e, e, 'down'));
  };

  const onMove = (e: PointerEvent): void => {
    if (!active.has(e.pointerId)) return;
    const coalesced = e.getCoalescedEvents?.();
    if (coalesced === undefined || coalesced.length === 0) {
      feed(sample(e, e, 'move'));
      return;
    }
    for (let i = 0; i < coalesced.length; i++) feed(sample(e, coalesced[i]!, 'move'));
  };

  const end = (e: PointerEvent, cancel: boolean): void => {
    if (active.delete(e.pointerId)) feed(sample(e, e, cancel ? 'cancel' : 'up'));
    if (attached) opts.onRawUp?.({ cancel, active: active.size });
  };
  const onUp = (e: PointerEvent): void => end(e, false);
  const onCancel = (e: PointerEvent): void => end(e, true);
  // One per adapter (it reads `attached`), so detaching one adapter never removes another adapter's listener.
  const preventDefault = (e: Event): void => {
    if (attached) e.preventDefault();
  };

  canvas.addEventListener('pointerdown', onDown, PASSIVE);
  canvas.addEventListener('pointermove', onMove, PASSIVE);
  canvas.addEventListener('pointerup', onUp, PASSIVE);
  canvas.addEventListener('pointercancel', onCancel, PASSIVE);
  canvas.addEventListener('contextmenu', preventDefault);
  canvas.addEventListener('selectstart', preventDefault);

  return {
    detach(): void {
      if (!attached) return;
      attached = false;
      canvas.removeEventListener('pointerdown', onDown, PASSIVE);
      canvas.removeEventListener('pointermove', onMove, PASSIVE);
      canvas.removeEventListener('pointerup', onUp, PASSIVE);
      canvas.removeEventListener('pointercancel', onCancel, PASSIVE);
      canvas.removeEventListener('contextmenu', preventDefault);
      canvas.removeEventListener('selectstart', preventDefault);
      for (const id of active) {
        try {
          if (canvas.hasPointerCapture(id)) canvas.releasePointerCapture(id);
        } catch {
          // NotFoundError: the pointer is gone, and so is its capture.
        }
      }
      active.clear();
      state = initialRecState();
      for (const { name, value, priority } of saved) {
        if (value === '') style.removeProperty(name);
        else style.setProperty(name, value, priority);
      }
    },
    tick(): void {
      if (active.size === 0) return;
      feed({ id: TICK_ID, t: now(), x: 0, y: 0, type: 'tick' });
    },
  };
}
